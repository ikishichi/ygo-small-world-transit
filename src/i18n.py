LANGUAGE_NAMES = {
    "ja": "日本語",
    "en": "English",
    "ko": "한국어",
    "zh-CN": "简体中文",
}


def resolve_language(lang: str | None = None) -> str:
    """URLの対応言語を優先し、未指定・未対応なら日本語を表示する。"""
    return lang if lang in LANGUAGE_NAMES else "ja"


def get_request_locale(language: str) -> str:
    """表示言語に対応する遊戯王ニューロンの取得言語を返す。"""
    return "cn" if language == "zh-CN" else resolve_language(language)


